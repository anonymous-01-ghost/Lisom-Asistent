package dev.lisom.tts

/**
 * Local speech synthesis adapter. Implementations must not call a remote TTS service.
 *
 * The synthesizer generates normalized mono PCM and delegates playback to the host
 * platform. Keeping playback separate lets a host supply its own audio session or
 * test sink without moving platform APIs into common code.
 */
interface SpeechSynthesizer {
    suspend fun speak(text: String)
    suspend fun stop()

    /** Releases native/model and output resources. Safe to call more than once. */
    suspend fun release() = stop()
}

/** Platform audio sink for normalized mono PCM generated by an offline TTS engine. */
interface SpeechAudioOutput {
    suspend fun play(samples: FloatArray, sampleRateHz: Int)
    suspend fun stop()

    /** Releases output resources. Safe to call more than once. */
    suspend fun release() = stop()
}
